#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <windows.h>
#include <string.h>
#include <math.h>
#include <stdbool.h>

int main()
{
	//01
	int a = 7 % 2; // 7除以2的余数，%两端必须是整数
	int b = 7 / 2; // 7除以2的商

	//02.<<
	int a = 7;       //000000000 00000000 00000000 00000111
	int b = a << 1;  //000000000 00000000 00000000 00001110
	printf("a=%d\nb=%d\n", a, b);

	//03.<<
	int a = -7;      //111111111 11111111 11111111 11111001 -7的二进制补码表示
	int b = a << 1;  //111111111 11111111 11111111 11110010 
	printf("a=%d\nb=%d\n", a, b);

	//04.>>
	int a = -7;
	int b = a >> 1;
	printf("a=%d\nb=%d\n", a, b);

	//05.&
	int a = 3;            // 00000000 00000000 00000000 00000011
	int b = -5;			  // 11111111 11111111 11111111 11111011
	int c = a & b;        // 00000000 00000000 00000000 00000011
	printf("c=%d\n", c);

	//06.|
	int a = 3;            // 00000000 00000000 00000000 00000011
	int b = -5;			  // 11111111 11111111 11111111 11111011
	int c = a | b;        // 11111111 11111111 11111111 11111011 ---> 
						  // 11111111 11111111 11111111 11111010 ---> 10000000 00000000 00000000 00000101
	printf("c=%d\n", c);

	//07.^
	int a = 3;            // 00000000 00000000 00000000 00000011
	int b = -5;			  // 11111111 11111111 11111111 11111011
	int c = a ^ b;        // 11111111 11111111 11111111 11111000 --->
	                      // 11111111 11111111 11111111 11110111 ---> 10000000 00000000 00000000 00001000
	printf("c=%d\n", c);

	//08
	//(1)
	int a = 3;
	int b = 5;
	printf("交换前：a=%d, b=%d\n", a, b);
	a = a + b;
	b = a - b;
	a = a - b;
	printf("交换后：a=%d, b=%d\n", a, b);
	//(2)
	int a = 3;
	int b = 5;
	printf("交换前：a=%d, b=%d\n", a, b);
	a = a ^ b;//a=3^5
	b = a ^ b;//b=3^5^5=3
	a = a ^ b;//a=3^5^3=5
	printf("交换后：a=%d, b=%d\n", a, b);

	//09.~
	int a = 0;
	//00000000 00000000 00000000 00000000 - 补码
	//11111111 11111111 11111111 11111111 - ~a
	//11111111 11111111 11111111 11111110
	//10000000 00000000 00000000 00000001
	printf("%d\n", ~a);

	//10
	int a = 13;
	a |= (1 << 4);
	printf("%d\n", a);
	a &= (~(1 << 4));
	printf("%d\n", a);

	//11
	int a = 3;
	int b = ++a;
	printf("a=%d, b=%d\n", a, b);// a=4 b=4



	return 0;
}